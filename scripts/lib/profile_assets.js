// Generates the two browser data files the Planning page and the "Why this place?" panel read, from the committed profile bundle
// (data/profiles/). Nothing is typed in: the field contract, the rows and the zone positions come from files that tests check.
//
//   assets/profiles-data.js   field contract (compact), uncertainty classes, the limits list, district rows. Small; loaded by Explore and Planning.
//   assets/planning-data.js   ward rows, per-ward zone context, simplified ward outlines projected to a 1000-unit map, crash-zone positions. Loaded by Planning.

const fs = require('fs');
const path = require('path');
const turf = require('@turf/turf');

const ROOT = path.join(__dirname, '..', '..');
const read = f => JSON.parse(fs.readFileSync(path.join(ROOT, f), 'utf8'));

function compactFields(fields) {
  const o = {};
  fields.forEach(f => { o[f.id] = [f.label, f.unit, f.uncertainty, f.source, f.dataYear, f.blankMeans, f.group]; });
  return o;
}

function build() {
  const schema = read('data/profiles/schema.json');
  const wards = read('data/profiles/ward_profiles.json');
  const districts = read('data/profiles/district_profiles.json');
  const header = '/* Generated by scripts/build_site.js from data/profiles/. Do not edit; run: node scripts/build_site.js */\n';

  const profiles = {
    dataVersion: schema.dataVersion,
    uncertaintyClasses: schema.uncertaintyClasses,
    cannotEstablish: schema.cannotEstablish,
    schema: { ward: compactFields(schema.wardFields), district: compactFields(schema.districtFields), zone: schema.zoneFields.map(z => [z.id, z.label, z.uncertainty]) },
    districtRows: districts.rows
  };

  // ward outlines: simplified (about 70 m), projected equirectangularly to a 1000-unit-wide map
  const geo = read('data/profiles/ward_profiles.geojson');
  const simple = turf.simplify(geo, { tolerance: 0.0006, highQuality: false, mutate: false });
  let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
  simple.features.forEach(f => f.geometry.coordinates.forEach(ring => ring.forEach(p => { x0 = Math.min(x0, p[0]); x1 = Math.max(x1, p[0]); y0 = Math.min(y0, p[1]); y1 = Math.max(y1, p[1]); })));
  const lat0 = (y0 + y1) / 2, cosLat = Math.cos(lat0 * Math.PI / 180);
  const k = 1000 / ((x1 - x0) * cosLat);
  const proj = p => [Math.round((p[0] - x0) * cosLat * k * 10) / 10, Math.round((y1 - p[1]) * k * 10) / 10];
  const pathOf = f => f.geometry.coordinates.map(ring => ring.map((p, i) => (i === 0 ? 'M' : 'L') + proj(p).join(' ')).join('') + 'Z').join('');
  const height = Math.round((y1 - y0) * k);
  const mPerUnit = Math.round(111320 * cosLat / (cosLat * k));

  const cols = Object.keys(wards.rows[0]).filter(c => c !== 'zones');
  const zonesGeo = read('data/delhi_crash_prone_zones_2024_all_named_approx.geojson');
  const zones = zonesGeo.features.map(f => {
    const p = f.properties;
    return [p.location_name, f.geometry.coordinates[1], f.geometry.coordinates[0], p.all_fatal_crashes == null ? null : p.all_fatal_crashes, p.all_total_crashes == null ? null : p.all_total_crashes, p.estimated_accuracy_m == null ? null : p.estimated_accuracy_m, p.coordinate_confidence || null]
      .concat(proj(f.geometry.coordinates));
  });
  const planning = {
    dataVersion: schema.dataVersion, viewBox: '0 0 1000 ' + height, metersPerUnit: mPerUnit, cols: cols,
    wards: wards.rows.map((r, i) => ({ no: r.ward_no, path: pathOf(simple.features[i]), v: cols.map(c => r[c]), zones: r.zones })),
    zonePoints: zones
  };
  return {
    'assets/profiles-data.js': header + 'window.DSO_PROFILES = ' + JSON.stringify(profiles) + ';\n',
    'assets/planning-data.js': header + 'window.DSO_PLAN = ' + JSON.stringify(planning) + ';\n'
  };
}

module.exports = { build };
